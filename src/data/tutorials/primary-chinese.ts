import type { Diagram, Example, Question, Tutorial } from './types';

const choice = (
  id: string,
  question: string,
  options: string[],
  answer: string,
  explanation: string,
  difficulty: Question['difficulty'] = 'easy'
): Question => ({ id, type: 'choice', question, options, answer, explanation, difficulty });

const fill = (
  id: string,
  question: string,
  answer: string | string[],
  explanation: string,
  difficulty: Question['difficulty'] = 'easy'
): Question => ({ id, type: 'fill', question, answer, explanation, difficulty });

const truefalse = (
  id: string,
  question: string,
  answer: '对' | '错',
  explanation: string,
  difficulty: Question['difficulty'] = 'easy'
): Question => ({ id, type: 'truefalse', question, answer, explanation, difficulty });

const solve = (
  id: string,
  question: string,
  answer: string,
  explanation: string,
  difficulty: Question['difficulty'] = 'medium'
): Question => ({ id, type: 'solve', question, answer, explanation, difficulty });


const svg = (content: string, caption?: string): Diagram => ({ type: 'svg', content, caption });

const example = (title: string, problem: string, solution: string, tip: string): Example => ({ title, problem, solution, tip });

