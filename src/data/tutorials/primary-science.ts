const fill = (
  id: string,
  question: string,
  answer: string | string[],
  explanation: string,
  difficulty: Question['difficulty'] = 'easy'
): Question => ({ id, type: 'fill', question, answer, explanation, difficulty });

const truefalse = (
  id: string,
  question: string,
  answer: '对' | '错',
  explanation: string,
  difficulty: Question['difficulty'] = 'easy'
): Question => ({ id, type: 'truefalse', question, answer, explanation, difficulty });

